// Run against a disposable empty data directory, never production work records.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'../frontend/node_modules/playwright');
const path=require('node:path');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const root=path.resolve(__dirname,'..');
const base=process.env.PLANNER_TEST_URL||'http://127.0.0.1:8766';
let activeBrowser;
let activePage;
let emptySandboxConfirmed=false;
async function main(){
  const browser=await chromium.launch({headless:true});activeBrowser=browser;
  const page=await browser.newPage({viewport:{width:1440,height:1050}});
  activePage=page;
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  await page.getByRole('heading',{name:'我的排柜'}).waitFor();
  const info=await (await page.request.get(base+'/api/bootstrap')).json();
  assert.equal(info.products.length+info.projects.length+info.imports.length,0,'E2E requires an empty disposable data directory');
  emptySandboxConfirmed=true;
  await page.getByRole('button',{name:'设置基础资料',exact:true}).click();
  async function upload(type,file){
    if(type)await page.getByRole('button',{name:type}).click();
    await page.getByLabel('选择Excel文件').setInputFiles(path.join(root,'.local-data/browser-fixtures',file));
    await page.getByRole('button',{name:'确认字段并导入'}).waitFor();
    await page.getByRole('button',{name:'确认字段并导入'}).click();
    await page.getByRole('heading',{name:type?'资料已导入':'订单审核',exact:true}).waitFor();
    if(!type)await page.getByRole('button',{name:'全部明细',exact:true}).click();
  }
  await upload(/产品排柜资料 编码/,'catalog.xlsx');
  await upload(/工厂产品表 按/,'factory.xlsx');
  await page.getByRole('button',{name:'我的排柜',exact:true}).click();
  await page.getByRole('button',{name:'新增订单',exact:true}).click();
  await upload(null,'order.xlsx');
  await page.getByRole('button',{name:'审核第2行 DCSYD',exact:true}).click();
  await page.getByLabel('调整后排柜数量').fill('705');
  await page.getByRole('button',{name:'＋ 添加批次'}).click();
  await page.getByLabel('本批次数量').first().fill('355');
  await page.getByRole('button',{name:'＋ 添加批次'}).click();
  assert.equal(await page.getByLabel('本批次数量').nth(1).inputValue(),'350');
  await page.getByRole('button',{name:'保存审核结果'}).click();
  await page.getByRole('button',{name:'进入排柜',exact:true}).waitFor();
  await page.getByRole('button',{name:'进入排柜',exact:true}).click();
  await page.getByRole('button',{name:'生成推荐方案'}).click();
  await page.getByRole('button',{name:'导出 Excel',exact:true}).waitFor();
  await page.waitForFunction(()=>document.querySelectorAll('.container-option').length===4);
  assert.match(await page.locator('.version-bar').innerText(),/已证明最优/);
  await page.screenshot({path:path.join(root,'.local-data/workspace.png'),fullPage:true});
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'导出 Excel',exact:true}).click();
  await (await download).saveAs(path.join(root,'.local-data/browser-download.xlsx'));
  await page.getByLabel('修改柜型').selectOption('20GP');
  await page.getByRole('button',{name:'另存新版本'}).click();
  await page.getByRole('alert').filter({hasText:'超体积'}).waitFor();
  await page.getByLabel('修改柜型').selectOption('40GP');
  await page.getByRole('button',{name:'另存新版本'}).click();
  await page.waitForFunction(()=>!document.querySelector('.version-bar')?.textContent.includes('有未保存调整'));
  await page.getByRole('button',{name:'锁定此柜',exact:true}).click();
  await page.getByRole('button',{name:'另存新版本'}).click();
  await page.waitForFunction(()=>!document.querySelector('.version-bar')?.textContent.includes('有未保存调整'));
  const beforeRecalculation=await page.locator('.version-bar select').inputValue();
  await page.getByRole('button',{name:'保留锁柜并重新排柜'}).click();
  await page.waitForFunction(previous=>{const current=document.querySelector('.version-bar select');return current&&current.value&&current.value!==previous;},beforeRecalculation);
  await page.waitForFunction(()=>document.querySelector('.container-heading')?.textContent.includes('解除锁定'));
  await page.getByRole('button',{name:'历史与备份',exact:true}).click();
  await page.getByRole('heading',{name:'Excel导出记录'}).waitFor();
  const backup=page.waitForEvent('download');
  await page.getByRole('link',{name:'备份全部资料'}).click();
  await (await backup).saveAs(path.join(root,'.local-data/browser-backup.zip'));
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'打开导航'}).click();
  await page.getByRole('button',{name:'我的排柜',exact:true}).click();
  await page.screenshot({path:path.join(root,'.local-data/mobile.png'),fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'mobile page must not overflow');
  assert.deepEqual(errors,[]);
  console.log('PASS: browser imports → review/split/adjust → solver → export → reject overload → save/lock/re-solve → backup → mobile');
  await browser.close();
}
main().catch(async e=>{console.error(e);if(activePage&&emptySandboxConfirmed){try{await activePage.screenshot({path:path.join(root,'.local-data/e2e-failure.png'),fullPage:true});console.error('Sandbox page:',await activePage.locator('body').innerText());}catch(captureError){console.error(captureError.message);}}await activeBrowser?.close();process.exitCode=1;});
