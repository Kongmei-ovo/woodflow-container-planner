// Disposable synthetic sandbox only. Runs after e2e_import.cjs.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'../frontend/node_modules/playwright');
const path=require('node:path');
const assert=require('node:assert/strict');
const base=process.env.PLANNER_TEST_URL;
let browser,page;
async function main(){
  assert.ok(base,'Explicit sandbox URL required');
  browser=await chromium.launch({headless:true});
  page=await browser.newPage({viewport:{width:1440,height:1050}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  await page.getByRole('heading',{name:'我的排柜',exact:true}).waitFor();
  const state=await(await page.request.get(base+'/api/bootstrap')).json();
  assert.equal(state.products.length,3);assert.ok(state.products.every(p=>['A','B','C'].includes(p.code)&&p.description.startsWith('TEST ')));
  const target=state.projects.find(p=>p.name==='grouped-order');assert.ok(target);
  const plan=state.plans.filter(p=>p.project_id===target.id).at(-1);assert.ok(plan);
  let row=page.locator(`tr[data-order-id="${target.id}"]`);
  await row.getByRole('button',{name:'编辑',exact:true}).click();
  const modal=page.getByRole('dialog',{name:'编辑订单信息'});
  await modal.getByLabel('订单名称',{exact:true}).fill('TEST renamed-order');
  await modal.getByLabel('客户',{exact:true}).fill('TEST customer');
  await modal.getByLabel('备注',{exact:true}).fill('TEST searchable notes');
  await modal.getByRole('button',{name:'保存订单信息',exact:true}).click();
  await row.getByText('TEST renamed-order',{exact:true}).waitFor();
  await page.getByRole('button',{name:/^回收站/}).click();
  await page.getByRole('button',{name:/^订单列表/}).click();
  const search=page.getByRole('textbox',{name:'搜索订单名称、客户或备注'});
  await search.fill('searchable notes');
  assert.equal(await page.locator('.orders-table tbody tr').count(),1);
  await page.getByLabel('处理状态',{exact:true}).selectOption('planned');
  assert.equal(await row.count(),1);
  await page.getByLabel('处理状态',{exact:true}).selectOption('review');
  await page.getByRole('heading',{name:'没有符合筛选条件的订单'}).waitFor();
  await page.getByRole('button',{name:'清空筛选',exact:true}).first().click();
  await page.getByLabel('工厂',{exact:true}).selectOption(target.factories[0]);
  await page.getByLabel('目的仓',{exact:true}).selectOption(target.warehouses[0]);
  assert.equal(await row.count(),1);
  await page.getByLabel('创建日期从',{exact:true}).fill('2099-01-01');
  await page.getByRole('heading',{name:'没有符合筛选条件的订单'}).waitFor();
  await page.getByRole('button',{name:'清空筛选',exact:true}).first().click();
  await row.getByRole('button',{name:'查看明细',exact:true}).click();
  await page.getByRole('heading',{name:'订单审核',exact:true}).waitFor();
  await page.getByRole('button',{name:'全部明细',exact:true}).click();
  await page.getByRole('button',{name:'我的排柜',exact:true}).click();
  page.once('dialog',d=>d.dismiss());
  await row.getByRole('button',{name:'删除',exact:true}).click();
  assert.equal(await row.count(),1,'Cancel delete must preserve order');
  page.once('dialog',d=>d.accept());
  await row.getByRole('button',{name:'删除',exact:true}).click();
  await row.waitFor({state:'hidden'});
  let current=await(await page.request.get(base+'/api/bootstrap')).json();
  assert.ok(!current.projects.some(p=>p.id===target.id));
  assert.ok(!current.plans.some(p=>p.id===plan.id));
  await page.getByRole('button',{name:/^回收站/}).click();
  await row.getByRole('button',{name:'恢复订单',exact:true}).click();
  await row.waitFor({state:'hidden'});
  await page.getByRole('button',{name:/^订单列表/}).click();
  await row.waitFor();
  await row.getByRole('button',{name:'打开方案',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.container-option').length===8);
  assert.equal(await page.locator('.version-bar select').inputValue(),plan.id);
  await page.getByRole('button',{name:'我的排柜',exact:true}).click();
  await page.locator('.order-list').screenshot({path:path.join(__dirname,'../.local-data/manual-orders.png')});
  await page.setViewportSize({width:1280,height:800});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Order list must not overflow the desktop page');
  assert.deepEqual(errors,[]);
  console.log('PASS: order list → edit metadata → search/status/factory/warehouse/date filters → details → cancel/delete → recycle bin → restore original plan');
  await browser.close();
}
main().catch(async error=>{console.error(error);if(page){try{await page.screenshot({path:path.join(__dirname,'../.local-data/e2e-failure.png'),fullPage:true});console.error(await page.locator('body').innerText());}catch{}}await browser?.close();process.exitCode=1;});
