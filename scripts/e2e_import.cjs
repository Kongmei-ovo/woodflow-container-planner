  assert.ok(project);
  const details=await(await page.request.get(base+'/api/projects/'+project.id)).json();
  assert.equal(details.lines.length,8);
  assert.equal(details.lines.reduce((sum,l)=>sum+l.original_qty,0),570);
  assert.equal(details.issue_count,0);
  assert.equal(await page.locator('.project-bar select').inputValue(),project.id);
  assert.equal(await page.evaluate(()=>localStorage.getItem('woodflow.project.v1')),project.id);
  assert.equal(await page.evaluate(()=>localStorage.getItem('woodflow.plan.v1')),'');
  await steps.getByRole('button',{name:/3 排柜并导出/}).click();
  await page.getByRole('heading',{name:'排柜工作台',exact:true}).waitFor();
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
