  const importGate=new Promise(resolve=>{releaseImport=resolve;});
  const importRequest=new Promise(resolve=>{importStarted=resolve;});
  const importFinished=new Promise(resolve=>{importHandled=resolve;});
  await page.route('**/api/bootstrap',async route=>{
    importStarted();await importGate;
    const response=await route.fetch();await route.fulfill({response});importHandled();
  });
  await page.getByRole('button',{name:'确认字段并导入',exact:true}).click();
  await signal(importRequest,'Imported order refresh');
  await page.getByRole('button',{name:'我的排柜',exact:true}).click();
  await page.getByRole('button',{name:'打开方案',exact:true}).first().click();
  await page.waitForFunction(()=>document.querySelectorAll('.container-option').length===8);
  releaseImport();await signal(importFinished,'Background import completion');await page.unroute('**/api/bootstrap');
  await page.getByText('正在同步当前订单…',{exact:true}).waitFor({state:'hidden'});
  await page.getByRole('heading',{name:'排柜工作台',exact:true}).waitFor();
  assert.equal(await page.locator('.solve-bar select').inputValue(),project.id,'A late import must not override a newer user selection');
  assert.equal(await page.locator('.version-bar select').inputValue(),newPlanId);
  const finalState=await(await page.request.get(base+'/api/bootstrap')).json();
