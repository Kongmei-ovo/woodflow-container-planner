// Uses only the disposable sandbox populated by e2e.cjs and synthetic fixtures.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'../frontend/node_modules/playwright');
const path=require('node:path');
const assert=require('node:assert/strict');
const base=process.env.PLANNER_TEST_URL||'http://127.0.0.1:8766';
const root=path.resolve(__dirname,'..');
let browser,page,sandboxConfirmed=false;
async function main(){
  browser=await chromium.launch({headless:true});
  page=await browser.newPage({viewport:{width:1440,height:1050}});
  await page.goto(base);
  const state=await(await page.request.get(base+'/api/bootstrap')).json();
  assert.equal(state.products.length,3);
  assert.ok(state.products.every(p=>['A','B','C'].includes(p.code)&&p.description.startsWith('TEST ')),'Import acceptance requires synthetic sandbox records');
  sandboxConfirmed=true;
  await page.getByRole('button',{name:'新建排柜',exact:true}).click();
  await page.getByLabel('选择Excel文件').setInputFiles(path.join(root,'.local-data/browser-fixtures/grouped-order.xlsx'));
  await page.getByLabel('工作表',{exact:true}).waitFor();
  assert.equal(await page.getByLabel('工作表',{exact:true}).inputValue(),'订单');
  assert.equal(await page.getByLabel('表头所在行',{exact:true}).inputValue(),'2');
  assert.equal(await page.getByLabel('DCSYD 数量',{exact:true}).inputValue(),'E');
  const confirm=page.getByRole('button',{name:'确认字段并导入',exact:true});
  assert.equal(await confirm.isEnabled(),true);
  await page.getByLabel('DCSYD 数量',{exact:true}).selectOption('J');
  assert.equal(await confirm.isDisabled(),true);
  await page.getByText('选中的数量列属于CBM体积区，请改选订购件数列。',{exact:true}).waitFor();
  await page.getByLabel('工作表',{exact:true}).selectOption('产品资料');
  await page.getByText(/当前工作表更像产品资料表/).waitFor();
  assert.equal(await confirm.isDisabled(),true);
  await page.getByLabel('工作表',{exact:true}).selectOption('订单');
  const header=page.getByLabel('表头所在行',{exact:true});
  await header.fill('1');
  assert.equal(await confirm.isDisabled(),true);
  await page.getByRole('button',{name:'更新预览',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('.mapping-grid select')?.value);
  await header.fill('2');
  await page.getByRole('button',{name:'更新预览',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.mapping-grid select')?.value==='A');
  assert.equal(await page.getByLabel('DCSYD 数量',{exact:true}).inputValue(),'E');
  await page.screenshot({path:path.join(root,'.local-data/import-groups.png'),fullPage:true});
  await confirm.click();
  await page.getByRole('button',{name:'进入订单审核',exact:true}).click();
  await page.getByRole('heading',{name:'订单审核',exact:true}).waitFor();
  const fresh=await(await page.request.get(base+'/api/bootstrap')).json();
  const project=fresh.projects.find(p=>p.name==='grouped-order');
  assert.ok(project);
  const details=await(await page.request.get(base+'/api/projects/'+project.id)).json();
  assert.equal(details.lines.length,8);
  assert.equal(details.lines.reduce((sum,l)=>sum+l.original_qty,0),570);
  assert.equal(details.issue_count,0);
  console.log('PASS: choose order sheet → distinguish pieces/CBM → reject product sheet → change header → import correct warehouse quantities');
  await browser.close();
}
main().catch(async error=>{console.error(error);if(page&&sandboxConfirmed){try{await page.screenshot({path:path.join(root,'.local-data/e2e-failure.png'),fullPage:true});console.error(await page.locator('body').innerText());}catch{}}await browser?.close();process.exitCode=1;});
