// Uses only the disposable sandbox populated by e2e.cjs and synthetic fixtures.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'../frontend/node_modules/playwright');
const path=require('node:path');
const assert=require('node:assert/strict');
const base=process.env.PLANNER_TEST_URL||'http://127.0.0.1:8766';
const root=path.resolve(__dirname,'..');
let browser,page,sandboxConfirmed=false;
